-- ============================================================
-- Bâtisseur — schéma complet de la base de données
-- (Supabase / PostgreSQL — à exécuter dans SQL Editor)
--
-- Script IDEMPOTENT : peut être exécuté plusieurs fois sans risque.
-- Il crée toutes les tables et colonnes nécessaires à ce jour.
-- Si votre base contient déjà certaines tables, les lignes
-- « create table if not exists » et « add column if not exists »
-- les laissent intactes et n'ajoutent que ce qui manque.
-- ============================================================

-- --- Mémoire durable : conversations et sites générés ---
create table if not exists conversations (
  id text primary key,
  data jsonb,
  updated_at timestamptz default now()
);

create table if not exists sites (
  id text primary key,
  html text,
  updated_at timestamptz default now()
);

-- --- Comptes de la plateforme (apprenants et formateurs) ---
create table if not exists users (
  id text primary key,
  email text unique,
  name text,
  pass text,
  status text default 'active',
  cohort text,
  cohort_id text,
  premium boolean default false,
  created_at timestamptz default now()
);
alter table users add column if not exists status text default 'active';
alter table users add column if not exists cohort text;
alter table users add column if not exists cohort_id text;
alter table users add column if not exists premium boolean default false;

create table if not exists sessions (
  token text primary key,
  user_id text,
  created_at timestamptz default now()
);

-- --- Certificats vérifiables ---
create table if not exists certificates (
  num text primary key,
  data jsonb,
  created_at timestamptz default now()
);

-- --- Sessions de formation (dates, capacité) ---
create table if not exists cohorts (
  id text primary key,
  data jsonb,
  created_at timestamptz default now()
);

-- --- Données reçues par les applications (commandes, rendez-vous, messages) ---
create table if not exists submissions (
  id text primary key,
  project_id text,
  collection text,
  data jsonb,
  status text default 'nouveau',
  created_at timestamptz default now()
);
alter table submissions add column if not exists status text default 'nouveau';

-- --- Fichiers joints reçus par les applications (photos, PDF, documents) ---
create table if not exists uploads (
  id text primary key,
  project_id text,
  name text,
  type text,
  size bigint,
  data text,                 -- contenu du fichier encodé en base64
  created_at timestamptz default now()
);

-- --- Réglages de la formation (lien de paiement Wave, prix, ouverture) ---
create table if not exists settings (
  id text primary key,
  data jsonb,
  updated_at timestamptz default now()
);

-- --- Réservations de session avec paiement (garder sa place) ---
create table if not exists reservations (
  id text primary key,
  cohort_id text,
  name text,
  email text,
  whatsapp text,
  status text default 'en_attente',   -- en_attente | paiement_declare | admis | file_attente | annule
  source text,                          -- en_ligne | especes
  declared_at timestamptz,
  admitted_at timestamptz,
  reminded_at timestamptz,
  created_at timestamptz default now()
);

-- --- Assiduité : temps de travail quotidien par apprenant (secondes/jour) ---
create table if not exists activity (
  user_id text not null,
  day date not null,
  seconds integer not null default 0,
  updated_at timestamptz default now(),
  primary key (user_id, day)
);

-- --- Résultats de l'examen de programmation (QCM) ---
create table if not exists quiz_results (
  user_id text not null,
  quiz text not null,
  score integer default 0,
  total integer default 0,
  passed boolean default false,
  updated_at timestamptz default now(),
  primary key (user_id, quiz)
);

-- --- Journal des visites du site (qui est passé) ---
create table if not exists visits (
  id bigint generated by default as identity primary key,
  at timestamptz,
  path text,
  page text,
  ip text,
  browser text,
  os text,
  device text,
  ref text,
  who text                    -- e-mail si la personne est connectée, sinon vide
);
create index if not exists visits_at_idx on visits (at desc);

-- --- Comptes des visiteurs des applications (espace membre) ---
create table if not exists app_users (
  id text primary key,
  app_id text,
  email text,
  name text,
  pass text,
  created_at timestamptz default now()
);

create table if not exists app_sessions (
  token text primary key,
  app_id text,
  user_id text,
  created_at timestamptz default now()
);
